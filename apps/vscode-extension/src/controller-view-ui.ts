import type { ControllerUI } from "./controller.js";
import type { ChatView } from "./chat-view.js";
/** Both hosts project controller events through the same retained conversation view. */
export function createControllerViewUI(view: Pick<ChatView, "appendMessage" | "appendChunk" | "showThinking" | "updateThinking" | "hideThinking" | "setInputEnabled" | "renderChatAdmission" | "renderHistoryState" | "renderThreadList" | "clearThread" | "showRewindPreview" | "prefillComposer" | "resolveInlineChangeCard" | "updateThreadTitle" | "appendThinkingEntry" | "appendThinkingChunk" | "finalizeAgentMessage" | "renderLiveGates" | "clearLiveGates" | "renderLivePlan" | "clearLivePlan" | "appendToolEvent" | "appendToolResult" | "updateWorkbar" | "updateRetryStatus" | "updateTokenProgress" | "updateEditFailure" | "renderLiveReview" | "clearLiveReview" | "renderLiveError" | "clearLiveError" | "renderLiveTodos" | "renderProviderAccess" | "clearLiveTodos" | "renderLiveSessions" | "clearLiveSessions" | "sendLiveStatus" | "replaceMessages" | "markQueued" | "removeMessage" | "restoreDraft" | "renderAgents" | "agentDetail" | "agentEvent" | "renderThreadUsage" | "renderApproval" | "retryDecision" | "renderContextUsage" | "renderTeams" | "renderLiveTeams" | "teamDetail" | "teamEvent">): Pick<ControllerUI,
"appendChatMessage" | "appendChatChunk" | "showChatThinking" | "updateChatThinking" | "hideChatThinking" | "setChatInputEnabled" | "renderChatAdmission" | "renderHistoryState" | "renderChatThreadList" | "clearChatThread" | "showRewindPreview" | "prefillComposer" | "resolveInlineChangeCard" | "updateThreadTitle" | "appendChatThinkingEntry" | "appendChatThinkingChunk" | "finalizeAgentMessage" | "renderLiveGates" | "clearLiveGates" | "renderLivePlan" | "clearLivePlan" | "appendToolEvent" | "appendToolResult" | "updateWorkbar" | "updateRetryStatus" | "updateTokenProgress" | "updateEditFailure" | "renderLiveReview" | "clearLiveReview" | "renderLiveError" | "clearLiveError" | "renderLiveTodos" | "renderProviderAccess" | "clearLiveTodos" | "renderLiveSessions" | "clearLiveSessions" | "sendLiveStatus" | "replaceChatMessages" | "markQueued" | "removeChatMessage" | "restoreDraft" | "renderAgents" | "agentDetail" | "agentEvent" | "renderThreadUsage" | "renderApproval" | "retryDecision" | "renderContextUsage" | "renderTeams" | "renderLiveTeams" | "teamDetail" | "teamEvent"> {
  return {
    appendChatMessage: (message) => view.appendMessage(message),
    appendChatChunk: (chunk) => view.appendChunk(chunk),
    showChatThinking: (message) => view.showThinking(message),
    updateChatThinking: (message) => view.updateThinking(message),
    hideChatThinking: () => view.hideThinking(),
    setChatInputEnabled: (enabled) => view.setInputEnabled(enabled),
    renderChatAdmission: admission => view.renderChatAdmission(admission),
    renderHistoryState: history => view.renderHistoryState(history),
    renderChatThreadList: (threads, activeThreadId) => view.renderThreadList(threads, activeThreadId),
    clearChatThread: (threadId) => view.clearThread(threadId),
    showRewindPreview: (preview) => view.showRewindPreview(preview),
    prefillComposer: (text, draft) => view.prefillComposer(text, draft),
    resolveInlineChangeCard: (taskId, resolution) => view.resolveInlineChangeCard(taskId, resolution),
    updateThreadTitle: (threadId, title) => view.updateThreadTitle(threadId, title),
    appendChatThinkingEntry: (text) => view.appendThinkingEntry(text),
    appendChatThinkingChunk: (chunk) => view.appendThinkingChunk(chunk),
    finalizeAgentMessage: () => view.finalizeAgentMessage(),
    renderLiveGates: (gates) => view.renderLiveGates(gates),
    clearLiveGates: () => view.clearLiveGates(),
    renderLivePlan: (plan) => view.renderLivePlan(plan),
    clearLivePlan: () => view.clearLivePlan(),
    appendToolEvent: (event) => view.appendToolEvent(event),
    appendToolResult: (id, output, isError) => view.appendToolResult(id, output, isError),
    updateWorkbar: (info) => view.updateWorkbar(info),
    updateRetryStatus: (status) => view.updateRetryStatus(status),
    updateTokenProgress: (progress) => view.updateTokenProgress(progress),
    updateEditFailure: (failure) => view.updateEditFailure(failure),
    renderLiveReview: (review) => view.renderLiveReview(review),
    clearLiveReview: () => view.clearLiveReview(),
    renderLiveError: (error) => view.renderLiveError(error),
    clearLiveError: () => view.clearLiveError(),
    renderLiveTodos: (todos) => view.renderLiveTodos(todos),
    renderProviderAccess: (access) => view.renderProviderAccess(access),
    clearLiveTodos: () => view.clearLiveTodos(),
    renderLiveSessions: (sessions) => view.renderLiveSessions(sessions),
    clearLiveSessions: () => view.clearLiveSessions(),
    sendLiveStatus: (status, turnActive, extra) => view.sendLiveStatus(status, turnActive, extra),
    replaceChatMessages: (messages) => view.replaceMessages(messages),
    markQueued: (id) => view.markQueued(id),
    removeChatMessage: (id) => view.removeMessage(id),
    restoreDraft: (text, recovery) => view.restoreDraft(text, recovery),
    renderAgents: (agents) => view.renderAgents(agents),
    agentDetail: (agentId, detail) => view.agentDetail(agentId, detail),
    agentEvent: (agentId, event) => view.agentEvent(agentId, event),
    renderThreadUsage: (usage) => view.renderThreadUsage(usage),
    renderApproval: (approval) => view.renderApproval(approval),
    retryDecision: (threadId, kind, gateId) => view.retryDecision(threadId, kind, gateId),
    renderContextUsage: (usage, stale) => view.renderContextUsage(usage, stale),
    renderTeams: (teams) => view.renderTeams(teams),
    renderLiveTeams: (teams) => view.renderLiveTeams(teams),
    teamDetail: (teamId, detail) => view.teamDetail(teamId, detail),
    teamEvent: (teamId, event) => view.teamEvent(teamId, event),
  };
}
